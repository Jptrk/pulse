    [DllImport("user32.dll")]
    [return: MarshalAs(UnmanagedType.Bool)]
    public static extern bool UnregisterHotKey(nint hWnd, int id);

    public static bool TryGetMonitorRect(nint hWnd, out RECT monitor)
    {
        nint hMonitor = MonitorFromWindow(hWnd, hWnd == 0 ? MONITOR_DEFAULTTOPRIMARY : MONITOR_DEFAULTTONEAREST);
        var info = new MONITORINFO { cbSize = Marshal.SizeOf<MONITORINFO>() };
        bool ok = GetMonitorInfo(hMonitor, ref info);
        monitor = info.rcMonitor;
        return ok;
    }

    /// <summary>True if the window covers its whole monitor (borderless or exclusive fullscreen).</summary>
    public static bool CoversMonitor(nint hWnd)
    {
        if (hWnd == 0 || hWnd == GetShellWindow() || !GetWindowRect(hWnd, out RECT r) || !TryGetMonitorRect(hWnd, out RECT m))
            return false;
        return r.Left <= m.Left && r.Top <= m.Top && r.Right >= m.Right && r.Bottom >= m.Bottom;
    }

